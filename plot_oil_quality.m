
function fig = plot_oil_quality(quality)
% ПОБУДОВА ГРАФІКА ОЦІНЮВАННЯ ЯКОСТІ МАСЛА

fig = figure( ...
    'Name','Якість трансформаторного масла', ...
    'Color','w');

%% Відносні значення показників

bar(quality.ratio);
hold on;

% Умовна діагностична межа
plot([0.5 4.5],[1 1],'--','LineWidth',1.5);

%% Оформлення графіка

xticks(1:4);

xticklabels({ ...
    'Кислотне число', ...
    'Пробивна напруга', ...
    'Діелектричні втрати', ...
    'Міжфазний натяг'});

xtickangle(20);

ylabel('Відношення до умовної межі');

title('Оцінка якості трансформаторного масла');

legend('Показники масла', ...
       'Умовна межа', ...
       'Location','best');

grid on;

end
